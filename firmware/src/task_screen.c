void display_battery_level_icon(ssd1306_t * display,int avg,int max_pixel_width,int height,int pos_x,int pos_y,uint8_t percentege)
{
    
    if (percentege > 100) percentege = 100;
    if (percentege < 0) percentege = 100;

    int current_width = max_pixel_width * percentege / 100;

     ssd1306_fill_rect(display, pos_x,pos_y,current_width,height);

}



void task_screen(void *arg1, void *arg2, void *arg3)
{ 

    if (gpio_is_ready_dt(&led)) {
        gpio_pin_configure_dt(&led, GPIO_OUTPUT_INACTIVE);
    }

    if (!i2c_is_ready_dt(&screen)) {
        while(1) {
            gpio_pin_toggle_dt(&led);
            k_msleep(1000); 
        }
    }

    uint8_t ping_data = 0x00;
    int ret = i2c_write_dt(&screen, &ping_data, 1);

    if (ret != 0) {
        while(1) {
            gpio_pin_toggle_dt(&led);
            k_msleep(100); 
        }
    } 

    gpio_pin_set_dt(&led, 1); 
    
    ssd1306_t my_display = {
        .dev_i2c = screen, 
        .buffer = {0}
    };

    k_msleep(100);
    
    if (ssd1306_init(&my_display)) {
        ssd1306_clear(&my_display);
        
       
        // ssd1306_draw_string(&my_display, 10, 10, "TEST I2C", 2);

        k_msleep(1000);

   
        


    }
    RingBuf battery_buf;
    ring_buff_init(&battery_buf);



    for(;;) {
    int szum = (rand() % 300) - 150; 
    int mock_adc = mock_base_voltage + szum;

    ring_buff_write(&battery_buf, mock_adc);

    int avg = avg_ring_buff(&battery_buf);

    printk("ADC: %4d mV | Suma: %6d | Srednia: %4d mV\n", mock_adc, battery_buf.sum, avg);

    ssd1306_clear(&my_display);
        
    
    ssd1306_draw_bitmap(&my_display, 30, 0, 64, 64, battery_empty_64x64);

    display_battery_level_icon(&my_display,avg,70,24,35,22,3300,4200);

    ssd1306_update(&my_display);

    k_msleep(100);
        
    }
}

